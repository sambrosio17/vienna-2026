// Updates the list of app files the service worker saves for offline use, and bumps its VERSION.
// Run after adding or renaming files:  node scripts/precache.mjs
import fs from 'node:fs'; import path from 'node:path'; import { fileURLToPath } from 'node:url';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const walk = dir => fs.readdirSync(path.join(root, dir), { withFileTypes: true })
  .flatMap(e => e.isDirectory() ? walk(path.join(dir, e.name)) : [path.join(dir, e.name).split(path.sep).join('/')]);
const files = ['css', 'js', 'data', 'icons', 'tickets-enc'].flatMap(walk).sort();
const list = ["'./'", "'./index.html'", "'./manifest.webmanifest'", ...files.map(f => `'./${f}'`)];
const swPath = path.join(root, 'sw.js');
let sw = fs.readFileSync(swPath, 'utf8');
sw = sw.replace(/\/\/ <precache>[\s\S]*?\/\/ <\/precache>/, `// <precache> (generated by scripts/precache.mjs)\nconst CORE = [\n  ${list.join(',\n  ')}\n];\n// </precache>`);
sw = sw.replace(/const VERSION = 'vienna26-v(\d+)';/, (m, n) => `const VERSION = 'vienna26-v${+n + 1}';`);
fs.writeFileSync(swPath, sw);
console.log(sw.match(/const VERSION = '[^']+'/)[0], '·', list.length, 'files');
